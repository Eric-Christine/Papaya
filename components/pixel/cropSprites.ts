export function getCropStageAsset(cropId: CropId, stage: GrowthStage): PixelGridAsset {
  if (stage === 'seed') return STAGE_SEED_OVERLAY;
  if (stage === 'sprout') return STAGE_SPROUT_OVERLAY;
  const sprites = CROP_STAGE_SPRITES[cropId] ?? CROP_STAGE_SPRITES.zucchini;
  return sprites[stage];
}
